"""Explicit local demo entry point. Never imported or mounted by main.py."""
import os, secrets, time
from pathlib import Path
from urllib.parse import urlsplit
from fastapi import FastAPI, Request, HTTPException
from fastapi.responses import FileResponse, JSONResponse
from fastapi.exceptions import RequestValidationError
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel
from typing import Literal
from .store import Store
from .api import router

ROOT=Path(__file__).resolve().parent

class Login(BaseModel):
    account: Literal['demo-a','demo-b']

def create_demo(path=None):
    if os.getenv('AITA_CAR_DEMO')!='1':
        raise RuntimeError('AITA_CAR_DEMO=1 requerido. Solo demo local, sin identidad de producción.')
    path=path or ROOT.parent/'work'/'aita-car.sqlite'
    if path!=':memory:': Path(path).parent.mkdir(parents=True,exist_ok=True)
    store=Store(path); store.seed('demo-a'); store.seed('demo-b')
    sessions={}; app=FastAPI(title='AITA Car · demo local', docs_url='/docs')
    app.state.store=store

    @app.exception_handler(RequestValidationError)
    async def invalid_input(request, exc):
        return JSONResponse({'detail':'Revisa los campos: valores inválidos o fuera de rango'},422)

    @app.middleware('http')
    async def local_only(request:Request,call_next):
        # Host allowlist also blocks DNS rebinding. CLI binds loopback only.
        host=request.headers.get('host','')
        try: hostname=urlsplit('http://'+host).hostname
        except ValueError: hostname=None
        if hostname not in ('127.0.0.1','localhost','testserver'):
            return JSONResponse({'detail':'Demo disponible solo en localhost'},403)
        if request.method not in ('GET','HEAD','OPTIONS'):
            origin=request.headers.get('origin')
            if origin not in ('http://'+host,'https://'+host):
                return JSONResponse({'detail':'Origen no autorizado'},403)
            chunks=[]; size=0
            async for chunk in request.stream():
                size+=len(chunk)
                if size>16384: return JSONResponse({'detail':'Solicitud demasiado grande'},413)
                chunks.append(chunk)
            request._body=b''.join(chunks)
        response=await call_next(request)
        response.headers['Cache-Control']='no-store'
        response.headers['X-Content-Type-Options']='nosniff'
        response.headers['Referrer-Policy']='no-referrer'
        response.headers['Content-Security-Policy']="default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data:; connect-src 'self'; frame-src https://www.openstreetmap.org; object-src 'none'; frame-ancestors 'none'; base-uri 'self'"
        return response

    def identity(request:Request):
        token=request.cookies.get('aita_car_session'); session=sessions.get(token)
        if not session or session['expires']<time.time():
            if token: sessions.pop(token,None)
            raise HTTPException(401,'Inicia una sesión demo')
        return session['tenant']

    def start_session(account,request):
        for key,s in list(sessions.items()):
            if s['expires']<time.time(): sessions.pop(key,None)
        if len(sessions)>500: raise HTTPException(429,'Demasiadas sesiones demo')
        old=request.cookies.get('aita_car_session'); sessions.pop(old,None)
        token=secrets.token_urlsafe(32); sessions[token]={'tenant':account,'expires':time.time()+3600}
        response=JSONResponse({'demo':True,'account':account})
        response.set_cookie('aita_car_session',token,httponly=True,samesite='strict',max_age=3600)
        return response

    @app.get('/api/car/runtime')
    def runtime(): return {'requires_login':False}

    @app.post('/api/car/demo-login')
    def login(b:Login,request:Request):
        return start_session(b.account,request)

    @app.post('/api/car/start')
    def start(request:Request):
        # Identity is generated by the server; never accept a client tenant ID.
        account='local-'+secrets.token_urlsafe(24)
        response=start_session(account,request)
        with store.transaction():
            store.save_profile(account,{'name':'','plan':'basic','onboarding_completed':False,'trial_access':True})
        return response

    @app.post('/api/car/logout')
    def logout(request:Request):
        sessions.pop(request.cookies.get('aita_car_session'),None)
        response=JSONResponse({'ok':True}); response.delete_cookie('aita_car_session'); return response

    app.include_router(router(store,identity,demo=True))
    app.mount('/car/assets',StaticFiles(directory=ROOT/'assets'),name='car-assets')
    @app.get('/')
    @app.get('/car')
    def index(): return FileResponse(ROOT/'index.html')
    return app

if __name__=='__main__':
    import uvicorn
    uvicorn.run(create_demo(),host='127.0.0.1',port=8011)
